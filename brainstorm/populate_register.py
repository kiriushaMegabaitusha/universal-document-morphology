def clean(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def parse_sections(path: Path) -> dict[str, dict[str, str]]:
    txt = path.read_text(encoding="utf-8")
    parts = re.split(r"^#{1,4}\s+(P\d{2}-\d)\b.*$", txt, flags=re.M)
    out: dict[str, dict[str, str]] = {}
    for i in range(1, len(parts) - 1, 2):
        iid, body = parts[i], parts[i + 1]
        labels = list(re.finditer(r"^\s*(?:[-*]\s+)?\*\*(.+?)\*\*", body, re.M))
        fields: dict[str, str] = {}
        for j, lm in enumerate(labels):
            label = lm.group(1).strip()
            start = lm.end()
            end = labels[j + 1].start() if j + 1 < len(labels) else len(body)
            chunk = body[start:end].strip()
            if label in fields:  # repeated bare labels ([assumption] xN) accumulate
                fields[label] = fields[label] + "\n\n" + chunk
            else:
                fields[label] = chunk
        out[iid] = fields
    return out


def classify_statement(fields: dict[str, str]) -> str:
    for label, content in fields.items():
        if "statement" in label.lower() and "participant" not in label.lower():
            text = clean(content)
            text = re.sub(r"^`\[?idea\]?`?\s*[:\-]\s*", "", text)
            text = re.sub(r"^\[idea\]\s*[:\-]\s*", "", text)
            return text
    return ""


def classify_list(fields: dict[str, str], want: str) -> list[str]:
    """want: 'pred' -> predicted observations / disconfirmers; 'unc' -> assumptions + feasibility risk."""
    picked: list[str] = []
    for label, content in fields.items():
        low = label.lower()
        if "participant" in low:
            continue
        if want == "pred" and ("prediction" in low
                               or "predicted observation" in low
                               or "disconfirm" in low):
            items = [clean(b) for b in re.split(r"^\s*[-*]\s+", content, flags=re.M) if clean(b)]
            picked.extend(items or [clean(content)])
        elif want == "unc" and ("assumption" in low or "feasibility risk" in low):
            items = [clean(b) for b in re.split(r"^\s*[-*]\s+", content, flags=re.M) if clean(b)]
            picked.extend(items or [clean(content)])
    # strip soft prefixes, bound size
    cleaned = []
    for p in picked:
        p = re.sub(r"^\*?(assumption|prediction|fact|idea)\*?:\s*", "", p, flags=re.I)
        if len(p) > 1800:
            p = p[:1797] + "..."
        if p:
            cleaned.append(p)
    return cleaned[:6]


